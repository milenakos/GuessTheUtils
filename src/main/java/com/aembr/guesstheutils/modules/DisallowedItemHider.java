    final static List<ColorCollection<Item>> ALLOWED_COLLECTIONS = List.of(
        BANNER,
        DYE,
        WOOL,
        CARPET,
        DYED_TERRACOTTA,
        STAINED_GLASS,
        STAINED_GLASS_PANE
    );

    final static List<Integer> ALLOWED_IDS;

    static {
        List<Integer> ids = new ArrayList<>();
        ALLOWED_ITEMS.forEach(item -> ids.add(Item.getId(item)));
        ALLOWED_COLLECTIONS.forEach(col -> col.forEach(item -> ids.add(Item.getId(item))));
        ids.add(Item.getId(BED.pick(DyeColor.RED)));
        ALLOWED_IDS = List.copyOf(ids);
    }

    public static boolean isAllowed(Item item) {
        if ((GuessTheUtils.events.gameState.equals(GTBEvents.GameState.ROUND_BUILD)
            || GuessTheUtils.events.gameState.equals(GTBEvents.GameState.ROUND_PRE))
                && GuessTheUtilsConfig.CONFIG.instance().enableDisallowedItemHiderModule) {
            return ALLOWED_IDS.contains(Item.getId(item));
        }
        return true;
    }
